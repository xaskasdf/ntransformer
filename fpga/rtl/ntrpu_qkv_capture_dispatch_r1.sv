    output wire result_q_valid,
    input wire [63:0] command_v_address,
    input wire [63:0] command_v_base,
    input wire [63:0] command_v_bytes,
    input wire command_v_source_valid,
    input wire [63:0] command_v_source_sequence,
    input wire [63:0] command_v_source_epoch,
    input wire [31:0] command_v_source_position,
    input wire source_completion_valid,
    output wire source_completion_ready,
    input wire [3:0] source_status,
    input wire [63:0] source_sequence,
    input wire [63:0] source_epoch,
    input wire [31:0] source_position,
    input wire [31:0] source_coefficient_position,
    input wire [31:0] source_hls_status,
    input wire [9:0] source_beats,
    input wire source_result_valid,
