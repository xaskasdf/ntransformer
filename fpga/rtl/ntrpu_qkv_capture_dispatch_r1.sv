    typedef enum logic [2:0] {IDLE,CAPTURE,OFFER,RUN,DRAIN} state_t;
    state_t state;
    logic cancel_seen;
    logic [63:0] held_sequence,held_epoch,held_lease;
    logic [31:0] held_layer,held_position;
    wire capture_command_ready,capture_busy,capture_cancel_ready;
    wire capture_done,capture_ack,capture_result_valid,capture_revoked;
    wire [3:0] capture_status;
    wire [63:0] capture_sequence,capture_epoch;
    wire [31:0] capture_layer,capture_position;
    wire [11:0] capture_qk_words;
    wire [5:0] capture_v_beats;
    wire [7:0] capture_frames,capture_address;
    wire capture_ce,capture_q_valid;
    wire [511:0] capture_q;
    wire dispatch_command_ready,dispatch_busy,dispatch_cache_exclusive,dispatch_cancel_ready;
    wire dispatch_done,dispatch_result_valid,dispatch_q_valid,dispatch_revoked;
    wire [31:0] dispatch_q;
    wire retained_cancel=cancel_seen || (cancel_valid && state!=DRAIN);
    assign busy=state!=IDLE;
    assign cache_exclusive=busy;
    assign command_ready=state==IDLE && capture_command_ready && dispatch_command_ready;
    assign cancel_ready=busy && state!=DRAIN && !cancel_seen;
    assign completion_valid=state==RUN && dispatch_done;
    assign result_valid=state==RUN && dispatch_result_valid;
    assign result_q_valid=state==RUN && dispatch_q_valid;
    assign result_q=result_q_valid ? dispatch_q:32'd0;
    assign completion_revoked=dispatch_revoked;
    assign completion_capture_status=capture_status;
    assign completion_capture_qk_words=capture_qk_words;
    assign completion_capture_v_beats=capture_v_beats;
    always_ff @(posedge clk)begin
        if(!rst_n)begin
            state<=IDLE;cancel_seen<=0;held_sequence<=0;held_epoch<=0;held_lease<=0;held_layer<=0;held_position<=0;
        end else begin
            if(cancel_valid && cancel_ready)cancel_seen<=1;
            case(state)
                IDLE:if(command_valid && command_ready)begin
                    held_sequence<=command_sequence;held_epoch<=command_epoch;held_lease<=command_lease_base;
                    held_layer<=command_layer;held_position<=command_position;
                    cancel_seen<=cancel_valid;state<=CAPTURE;
                end
                CAPTURE:if(capture_done)state<=OFFER;
                OFFER:if(dispatch_command_ready)state<=RUN;
                RUN:if(dispatch_done && completion_ready)state<=DRAIN;
                DRAIN:if(!capture_busy && !dispatch_busy)begin cancel_seen<=0;state<=IDLE;end
                default:state<=DRAIN;
            endcase
        end
    end
    ntrpu_qkv_snapshot_r1 #(.WATCHDOG_CYCLES(WATCHDOG_CYCLES)) capture(
        .clk(clk),
        .rst_n(rst_n),
        .command_valid(state==IDLE && command_valid && command_ready),
        .command_ready(capture_command_ready),
        .command_sequence(command_sequence),
        .command_epoch(command_epoch),
        .expected_epoch(expected_epoch),
        .command_layer(command_layer),
        .command_position(command_position),
        .command_v_address(command_v_address),
        .command_v_base(command_v_base),
        .command_v_bytes(command_v_bytes),
        .command_v_source_valid(command_v_source_valid),
        .command_v_source_sequence(command_v_source_sequence),
        .command_v_source_epoch(command_v_source_epoch),
        .command_v_source_position(command_v_source_position),
        .source_completion_valid(source_completion_valid),
        .source_completion_ready(source_completion_ready),
        .source_status(source_status),
        .source_sequence(source_sequence),
        .source_epoch(source_epoch),
        .source_position(source_position),
        .source_coefficient_position(source_coefficient_position),
        .source_hls_status(source_hls_status),
        .source_beats(source_beats),
        .source_result_valid(source_result_valid),
        .source_ce(source_ce),
        .source_address(source_address),
        .source_q(source_q),
        .source_q_valid(source_q_valid),
        .cancel_valid(retained_cancel),
        .cancel_ready(capture_cancel_ready),
        .busy(capture_busy),
        .completion_valid(capture_done),
        .completion_ready(capture_ack),
        .completion_status(capture_status),
        .completion_sequence(capture_sequence),
        .completion_epoch(capture_epoch),
        .completion_layer(capture_layer),
        .completion_position(capture_position),
        .completion_qk_words(capture_qk_words),
        .completion_v_beats(capture_v_beats),
        .completion_frames(capture_frames),
        .result_valid(capture_result_valid),
        .completion_revoked(capture_revoked),
        .result_ce(capture_ce),
        .result_address(capture_address),
        .result_q(capture_q),
        .result_q_valid(capture_q_valid),
        .m_axi_araddr(m_axi_araddr),
        .m_axi_arlen(m_axi_arlen),
        .m_axi_arsize(m_axi_arsize),
        .m_axi_arprot(m_axi_arprot),
        .m_axi_arburst(m_axi_arburst),
        .m_axi_arid(m_axi_arid),
        .m_axi_arcache(m_axi_arcache),
        .m_axi_arlock(m_axi_arlock),
        .m_axi_arvalid(m_axi_arvalid),
        .m_axi_arready(m_axi_arready),
        .m_axi_rdata(m_axi_rdata),
        .m_axi_rresp(m_axi_rresp),
        .m_axi_rid(m_axi_rid),
        .m_axi_rlast(m_axi_rlast),
        .m_axi_rvalid(m_axi_rvalid),
        .m_axi_rready(m_axi_rready)
    );
    ntrpu_qkv_dispatch_r1 #(.WATCHDOG_CYCLES(WATCHDOG_CYCLES)) dispatch(
        .clk(clk),
        .rst_n(rst_n),
        .command_valid(state==OFFER),
        .command_ready(dispatch_command_ready),
        .command_sequence(held_sequence),
        .command_epoch(held_epoch),
        .command_lease_base(held_lease),
        .expected_epoch(expected_epoch),
        .command_layer(held_layer),
        .command_position(held_position),
        .cancel_valid(retained_cancel),
        .cancel_ready(dispatch_cancel_ready),
        .busy(dispatch_busy),
        .cache_exclusive(dispatch_cache_exclusive),
        .cache_idle(cache_idle),
        .cache_valid(cache_valid),
        .cache_metadata_fault(cache_metadata_fault),
        .cache_sequence(cache_sequence),
        .cache_epoch(cache_epoch),
        .cache_capacity(cache_capacity),
        .cache_committed_tokens(cache_committed_tokens),
        .source_completion_valid(capture_done),
