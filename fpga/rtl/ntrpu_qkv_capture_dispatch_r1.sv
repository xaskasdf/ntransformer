// Real Q/K/V snapshot followed by KV append and attention dispatch.
// Caller excludes all other cache users while cache_exclusive is high,
// including capture, held completion and final upstream-source drain.
// V storage and upstream RoPE RAM must remain immutable until release.
// Cache/lease admission is checked by the dispatcher after capture.
// Reset must quiesce both children, the upstream source and both AXI peers.
`default_nettype none
module ntrpu_qkv_capture_dispatch_r1 #(
    parameter integer WATCHDOG_CYCLES=65536
) (
    input wire clk,
    input wire rst_n,
    input wire command_valid,
    output wire command_ready,
