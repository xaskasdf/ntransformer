"""Generate the structural root wrapper; reject unclassified engine ports."""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
ENGINE = ROOT / 'fpga/rtl/vivado_explicit_nets_r1/ntrpu_attention_engine_r1.sv'
OUTPUT = ROOT / 'fpga/rtl/ntrpu_attention_root_r1.sv'


def render():
    raw = ENGINE.read_bytes()
    header = raw.decode().split(') (', 1)[1].split('\n);', 1)[0]
    ports = []
    for line in header.strip().splitlines():
        match = re.fullmatch(r'\s*(input wire logic|output logic)\s+(?:(\[\d+:0\])\s+)?(\w+),?', line)
        assert match, line
        ports.append(match.groups())
    names = {name for _, _, name in ports}
    assert len(names) == len(ports) == 102, len(ports)
    head_names = {n for n in names if n.startswith(('command_', 'cancel_', 'completion_', 'result_'))}
    removed = {'command_query', 'command_head', 'command_lease'}
    declarations = []
    for direction, width, name in ports:
        if name in removed:
            continue
        if name == 'result_address':
            width = '[10:0]'
        declarations.append(f'    {direction} {width+" " if width else ""}{name}')
    extras = [('input wire logic', '[63:0]', 'command_lease_base'),
              ('input wire logic', '', 'q_valid'), ('output logic', '', 'q_ready'),
              ('input wire logic', '[511:0]', 'q_data'), ('input wire logic', '[7:0]', 'q_index'),
              ('input wire logic', '', 'q_last'), ('input wire logic', '[63:0]', 'q_sequence'),
              ('input wire logic', '[63:0]', 'q_epoch'),
              ('output logic', '[63:0]', 'completion_sequence'),
              ('output logic', '[63:0]', 'completion_epoch'),
              ('output logic', '', 'cache_lock'), ('output logic', '', 'maintenance_busy'),
              ('output logic', '', 'metadata_fault'),
              ('output logic', '[31:0]', 'committed_tokens')]
    declarations += [f'    {d} {w+" " if w else ""}{n}' for d,w,n in extras]
    lines = ['// Generated by tools/build_ntrpu_attention_root_wrapper_r1.py.',
             '// Engine source SHA256: '+hashlib.sha256(raw).hexdigest(),
             '`default_nettype none',
             'module ntrpu_attention_root_r1 #(parameter integer WATCHDOG_CYCLES=65536) (',
             ',\n'.join(declarations), ');']
    for _, width, name in ports:
        if name in head_names:
            lines.append(f'    wire {width+" " if width else ""}head_{name};')
    for n in ['engine_bind_valid','engine_bind_ready','engine_append_valid','engine_append_ready',
              'engine_cache_valid','sequencer_command_valid','sequencer_command_ready']:
        lines.append('    wire '+n+';')

    def instance(module, name, mapping, parameter=False):
        lines.append('    '+module+(' #(.WATCHDOG_CYCLES(WATCHDOG_CYCLES))' if parameter else '')+' '+name+' (')
        lines.append(',\n'.join(f'        .{p}({value})' for p,value in mapping.items()))
        lines.append('    );')

    mapping = {n:('head_'+n if n in head_names else n) for _,_,n in ports}
    for n in ['bind_valid','bind_ready','append_valid','append_ready','cache_valid']:
        mapping[n]='engine_'+n
    instance('ntrpu_attention_engine_r1', 'engine', mapping, True)
    seq_names = ['clk','rst_n','command_layer','command_position','command_sequence','command_epoch',
                 'command_lease_base','cache_sequence','cache_epoch','expected_epoch','cache_capacity','cache_lock',
                 'q_valid','q_ready','q_data','q_index','q_last','q_sequence','q_epoch','cancel_valid','cancel_ready',
                 'completion_valid','completion_ready','completion_status','completion_sequence','completion_epoch',
                 'result_valid','result_ce','result_address','result_q','result_q_valid']
    seq={n:n for n in seq_names}
    seq.update(command_valid='sequencer_command_valid', command_ready='sequencer_command_ready',
               cache_idle='!maintenance_busy && !lease_active && !append_done_valid',
               cache_valid='cache_valid', cache_committed_tokens='committed_tokens')
    seq.update({'head_'+n:'head_'+n for n in sorted(head_names)})
    instance('ntrpu_attention_head_sequencer_r1', 'sequencer', seq, True)
    guard_names=['clk','rst_n','bind_valid','bind_ready','engine_bind_valid','engine_bind_ready',
                 'bind_sequence','bind_epoch','append_valid','append_ready','engine_append_valid',
                 'engine_append_ready','append_layer','append_position','append_sequence','append_epoch',
                 'command_valid','command_ready','sequencer_command_valid','sequencer_command_ready',
                 'command_layer','engine_cache_valid','expected_epoch','maintenance_busy','metadata_fault']
    guard={n:n for n in guard_names}
    guard.update(sequencer_cache_lock='cache_lock',engine_lease_active='lease_active',
                 trusted_cache_valid='cache_valid',trusted_committed_tokens='committed_tokens',
                 engine_cache_capacity='cache_capacity',engine_cache_sequence='cache_sequence',engine_cache_epoch='cache_epoch')
    guard.update({'engine_done_'+n:'append_done_'+n for n in
                 ['valid','ready','bind','status','bytes','committed_tokens','sequence','epoch']})
    instance('ntrpu_attention_root_guard_r1','guard',guard)
    lines += ['endmodule','`default_nettype wire','']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = render()
    if OUTPUT.exists():
        assert OUTPUT.read_text() == text, 'Refuse to overwrite a changed wrapper'
    else:
        OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(OUTPUT)
